"""Build the derived shoe dataset from the unchanged raw CSVs; run from the repository root.

Every source product maps to one shoe in its paired category (seeded weighted choice), and every order
line gets a size (seeded by its order_item_id), so the line points at one shoe SKU. Only identity and
money columns change; customers, order ids, dates, statuses and quantities are kept. Money is rescaled
to the shoe's list price and recomputed so the importer's three identities hold exactly. Output is
deterministic: same input and seed give byte-identical files. See docs/plans/shoe-sizes-catalogue.md.
"""
import argparse
import csv
from collections import defaultdict
from decimal import Decimal, ROUND_HALF_UP
import hashlib
from pathlib import Path
import random
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from catalogue.shoes import CATEGORY_MAP, SHOES, SIZE_WEIGHTS, SIZES, sku  # noqa: E402

CENT = Decimal("0.01")
OUTPUT_FILES = ("customers.csv", "products.csv", "orders.csv", "order_items.csv", "product_map.csv")
README = """# Derived shoe dataset

Generated by `analytics/build_shoe_dataset.py` (seed {seed}) from `data/raw/`, which is unchanged.
Only `checksums.txt` and `product_map.csv` are committed; regenerate the rest and compare checksums.

Source: Analytics Engineering, "Ecommerce Sales & Returns Dataset v1.0.0", CC BY 4.0
(see `data/raw/LICENSE.txt`). **Changes were made:** product identities, names, categories and prices
are replaced by a 20-shoe catalogue in 10 US sizes (`src/catalogue/shoes.py`); order-line product IDs,
unit prices, discounts and line totals, and order subtotals, taxes and totals are recomputed. Customers,
order IDs, dates, statuses, quantities and shipping amounts are unchanged. Payments and refunds are
omitted because their amounts no longer match.

- Category pairing (source to shoe): {pairing}.
- `product_map.csv`: each source product and the shoe it maps to (seeded weighted choice per category).
- Sizes are assigned per order line by a seeded weighted choice; they are synthetic, not real demand.
- `unit_price` = shoe list price x (source unit_price / source list_price); the discount keeps its source
  rate; tax keeps its source rate on the new subtotal. Decimal, ROUND_HALF_UP to cents.
"""


def money(value):
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def read(path):
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        return reader.fieldnames, list(reader)


def write(path, fields, rows):
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def map_products(products, seed):
    """Source product_id -> shoe row, chosen by weight among the shoes of the paired category."""
    by_category = defaultdict(list)
    for shoe in SHOES:
        by_category[shoe[2]].append(shoe)
    mapping = {}
    for row in sorted(products, key=lambda r: r["product_id"]):
        choices = by_category[CATEGORY_MAP[row["category"]]]
        rng = random.Random(f"{seed}:{row['product_id']}")
        mapping[row["product_id"]] = rng.choices(choices, weights=[shoe[6] for shoe in choices])[0]
    unused = {shoe[0] for shoe in SHOES} - {shoe[0] for shoe in mapping.values()}
    if unused:
        raise ValueError(f"shoes with no source product: {sorted(unused)}")
    return mapping


def size_for(order_item_id, seed):
    return random.Random(f"{seed}:{order_item_id}").choices(SIZES, weights=SIZE_WEIGHTS)[0]


def build(source, output, seed):
    output.mkdir(parents=True, exist_ok=True)
    _, products = read(source / "products.csv")
    order_fields, orders = read(source / "orders.csv")
    item_fields, items = read(source / "order_items.csv")
    list_price = {row["product_id"]: Decimal(row["list_price"]) for row in products}
    mapping = map_products(products, seed)

    new_lines = defaultdict(list)
    for row in items:
        shoe = mapping[row["product_id"]]
        quantity = int(row["quantity"])
        source_price = Decimal(row["unit_price"])
        unit_price = money(Decimal(shoe[3]) * source_price / list_price[row["product_id"]])
        source_gross = source_price * quantity
        rate = Decimal(row["discount_amount"]) / source_gross if source_gross else Decimal(0)
        discount = money(unit_price * quantity * rate)
        row.update(product_id=sku(shoe[0], size_for(row["order_item_id"], seed)), unit_price=f"{unit_price}",
                   discount_amount=f"{discount}", line_total=f"{unit_price * quantity - discount}")
        new_lines[row["order_id"]].append(Decimal(row["line_total"]))

    for row in orders:
        source_subtotal = Decimal(row["subtotal"])
        subtotal = sum(new_lines[row["order_id"]], Decimal("0.00"))
        rate = Decimal(row["tax_amount"]) / source_subtotal if source_subtotal else Decimal(0)
        tax = money(subtotal * rate)
        row.update(subtotal=f"{subtotal}", tax_amount=f"{tax}",
                   order_total=f"{subtotal + tax + Decimal(row['shipping_amount'])}")

    shoe_products = [{"product_id": sku(shoe_id, size), "sku": sku(shoe_id, size), "product_name": name,
                      "category": category, "unit_cost": cost, "list_price": price, "shoe_id": shoe_id,
                      "size": f"{size}"}
                     for shoe_id, name, category, price, cost, _, _ in SHOES for size in SIZES]

    shutil.copyfile(source / "customers.csv", output / "customers.csv")
    write(output / "products.csv", ["product_id", "sku", "product_name", "category", "unit_cost", "list_price",
                                    "shoe_id", "size"], shoe_products)
    write(output / "orders.csv", order_fields, sorted(orders, key=lambda r: r["order_id"]))
    write(output / "order_items.csv", item_fields, sorted(items, key=lambda r: r["order_item_id"]))
    write(output / "product_map.csv", ["source_product_id", "source_category", "shoe_id", "shoe_name"],
          [{"source_product_id": key, "source_category": next(p["category"] for p in products if p["product_id"] == key),
            "shoe_id": shoe[0], "shoe_name": shoe[1]} for key, shoe in sorted(mapping.items())])
    pairing = ", ".join(f"{key} to {value}" for key, value in CATEGORY_MAP.items())
    (output / "README.md").write_text(README.format(seed=seed, pairing=pairing), encoding="utf-8", newline="\n")
    checksums = "".join(f"{hashlib.sha256((output / name).read_bytes()).hexdigest()}  {name}\n" for name in OUTPUT_FILES)
    (output / "checksums.txt").write_text(checksums, encoding="utf-8", newline="\n")
    return checksums


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "data" / "raw")
    parser.add_argument("--output", type=Path, default=ROOT / "data" / "derived" / "shoes")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)
    if args.output.resolve() == args.source.resolve():
        raise SystemExit("output must differ from the raw source directory")
    print(build(args.source, args.output, args.seed), end="")


if __name__ == "__main__":
    main()
