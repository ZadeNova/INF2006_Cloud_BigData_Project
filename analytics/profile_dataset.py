"""Independent source acceptance audit; run from the repository root."""
import argparse
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
import hashlib
from pathlib import Path

import pandas as pd

COUNTS = {"customers": 20000, "products": 1200, "orders": 100000,
          "order_items": 237537, "payments": 105388, "refunds": 7910}
KEYS = {name: name[:-1] + "_id" for name in COUNTS}
STATUSES = {"completed": "completed", "cancelled": "cancelled",
            "refunded": "refunded", "partially_refunded": "refunded"}
MONEY = {"products": ["unit_cost", "list_price"],
         "orders": ["subtotal", "tax_amount", "shipping_amount", "order_total"],
         "order_items": ["unit_price", "discount_amount", "line_total"],
         "payments": ["amount"], "refunds": ["amount"]}


def money(value):
    try:
        result = Decimal(value)
        return result if result.is_finite() and result >= 0 else None
    except InvalidOperation:
        return None


def timestamp(value):
    try:
        result = pd.Timestamp(value)
        if pd.isna(result):
            return pd.NaT
        return result.tz_localize("Asia/Singapore") if result.tzinfo is None else result.tz_convert("Asia/Singapore")
    except (ValueError, TypeError):
        return pd.NaT


def profile(source):
    frames = {name: pd.read_csv(source / f"{name}.csv", dtype=str, keep_default_na=False)
              for name in COUNTS}
    findings = []
    checks = []

    def reject(table, mask, reason):
        for index in frames[table].index[mask]:
            findings.append((table, index + 2, frames[table].at[index, KEYS[table]], reason))

    for name, frame in frames.items():
        checks.append((name, COUNTS[name], len(frame), len(frame) == COUNTS[name]))
        reject(name, frame[KEYS[name]].eq("") | frame[KEYS[name]].duplicated(keep=False), "empty/duplicate primary ID")
        for field in MONEY.get(name, []):
            frame[field] = frame[field].map(money)
            reject(name, frame[field].isna(), f"{field}: invalid/nonfinite/negative money")
    for child, field, parent in [("orders", "customer_id", "customers"),
                                  ("order_items", "order_id", "orders"),
                                  ("order_items", "product_id", "products"),
                                  ("payments", "order_id", "orders"),
                                  ("refunds", "order_id", "orders"),
                                  ("refunds", "payment_id", "payments")]:
        reject(child, ~frames[child][field].isin(frames[parent][KEYS[parent]]), f"orphan {field}")
    orders, lines = frames["orders"], frames["order_items"]
    reject("orders", ~orders.order_status.isin(STATUSES), "unsupported order_status")
    for name, field in [("customers", "created_at"), ("orders", "ordered_at"),
                        ("payments", "paid_at"), ("refunds", "refunded_at")]:
        frames[name][field] = pd.to_datetime(frames[name][field].map(timestamp), utc=True).dt.tz_convert("Asia/Singapore")
        reject(name, frames[name][field].isna(), f"invalid {field}")
    quantities = pd.to_numeric(lines.quantity, errors="coerce")
    valid_quantity = quantities.notna() & quantities.between(1, 2147483647) & (quantities % 1 == 0)
    reject("order_items", ~valid_quantity, "nonpositive/noninteger/out-of-range quantity")
    lines["quantity"] = quantities
    # Decimal arithmetic avoids float tolerances hiding a monetary discrepancy.
    cents = Decimal("0.01")
    valid = lines.unit_price.notna() & lines.discount_amount.notna() & lines.line_total.notna() & valid_quantity
    lines["gross"] = [p.quantize(cents, rounding=ROUND_HALF_UP) * int(q) if ok else None
                      for p, q, ok in zip(lines.unit_price, quantities, valid)]
    reject("order_items", valid & ((lines.gross - lines.discount_amount) != lines.line_total), "line total != rounded unit price * quantity - discount")
    net = lines.groupby("order_id").line_total.sum()
    gross = lines.groupby("order_id").gross.sum()
    orders["line_net"] = orders.order_id.map(net)
    orders["line_gross"] = orders.order_id.map(gross)
    reject("orders", orders.line_net.isna() | (orders.line_net != orders.subtotal), "line net sum != subtotal / missing lines")
    valid_order = orders[MONEY["orders"]].notna().all(axis=1)
    reject("orders", valid_order & ((orders.subtotal + orders.tax_amount + orders.shipping_amount) != orders.order_total), "subtotal + tax + shipping != order_total")
    signup = frames["customers"].drop_duplicates("customer_id").set_index("customer_id").created_at
    reject("orders", orders.ordered_at < orders.customer_id.map(signup), "order before customer signup")

    output = ["# Dataset acceptance profile", "", "Generated by `analytics/profile_dataset.py`; no wall-clock fields. Raw files are unchanged.", "",
              "## Counts and checksums", "", "| Table | Published | Actual | Match | SHA-256 |", "|---|---:|---:|---|---|"]
    for name, published, actual, match in checks:
        checksum = hashlib.sha256((source / f"{name}.csv").read_bytes()).hexdigest()
        output.append(f"| {name} | {published} | {actual} | {match} | `{checksum}` |")
    output += ["", "## Dates", "", "Explicit offsets are preserved. Naive dates/timestamps assume Asia/Singapore.", ""]
    for name, field in [("customers", "created_at"), ("orders", "ordered_at"), ("payments", "paid_at"), ("refunds", "refunded_at")]:
        values = frames[name][field]
        output.append(f"- {name}.{field}: {values.min()} through {values.max()}.")
    utc_dates = orders.ordered_at.dt.tz_convert("UTC")
    coverage_ok = str(utc_dates.min().date()) == "2023-01-01" and str(utc_dates.max().date()) == "2025-12-31"
    output += [f"- Published UTC order coverage 2023-01-01..2025-12-31 matches: {coverage_ok}.", "",
               "## Integrity and rejections", "", f"Rejected rows: {len(set((t, r) for t, r, _, _ in findings))}; reasons: {len(findings)}.",
               "Checks: unique primary IDs, all six-table foreign keys, supported order statuses, finite nonnegative money, positive integer quantities, signup chronology, exact decimal line/order reconciliation.", "",
               "| Table | CSV row | External ID | Reason |", "|---|---:|---|---|"]
    output += [f"| {t} | {r} | {key} | {reason} |" for t, r, key, reason in sorted(findings)] or ["| — | — | — | None |"]
    output += ["", "## Status mapping and monetary reconciliation", "", "| Source status | Application status | Orders | Source total | Net lines | Application gross lines |", "|---|---|---:|---:|---:|---:|"]
    for status, group in orders.groupby("order_status", sort=True):
        output.append(f"| {status} | {STATUSES.get(status, 'REJECT')} | {len(group)} | {group.order_total.sum():.2f} | {group.line_net.sum():.2f} | {group.line_gross.sum():.2f} |")
    output += ["", "Application totals exclude discounts, tax and shipping; differences from source order_total are intentional, not reconciliation failures. Partially refunded orders map to refunded and are excluded from completed sales."]
    dates = orders.ordered_at.dt.normalize()
    spine = pd.date_range(dates.min(), dates.max(), freq="D")
    daily = dates.value_counts().reindex(spine, fill_value=0).sort_index()
    output += ["", "## Analytics signal", "", f"Daily orders ({len(spine)} Singapore dates, including zeros): min {daily.min()}, mean {daily.mean():.3f}, max {daily.max()}, population variance {daily.var(ddof=0):.3f}.", "",
               "| Weekday | Mean daily orders |", "|---|---:|"]
    weekly = daily.groupby(daily.index.dayofweek).mean()
    output += [f"| {['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'][day]} | {value:.3f} |" for day, value in weekly.items()]
    output.append(f"\nWeekday max/min mean ratio: {weekly.max() / weekly.min():.3f}. This describes synthetic patterns, not proven seasonality.")
    completed = orders[orders.order_status == "completed"][["order_id", "ordered_at"]]
    sales = lines.merge(completed, on="order_id", how="inner")
    sales["date"] = sales.ordered_at.dt.normalize()
    unit_days = sales.groupby(["product_id", "date"]).quantity.sum().unstack(fill_value=0).reindex(index=frames["products"].product_id, columns=spine, fill_value=0)
    output += ["", "| Product | Completed units | Active sales dates | Daily unit variance (zeros included) | Historical unit price count | Min price | Max price |", "|---|---:|---:|---:|---:|---:|---:|"]
    prices = lines.groupby("product_id").unit_price.agg(["nunique", "min", "max"])
    for product, row in unit_days.iterrows():
        p = prices.loc[product] if product in prices.index else None
        output.append(f"| {product} | {row.sum():.0f} | {(row > 0).sum()} | {row.var(ddof=0):.6f} | {p['nunique'] if p is not None else 0} | {p['min'] if p is not None else 'n/a'} | {p['max'] if p is not None else 'n/a'} |")
    output += ["", "Prices above use all historical lines, including excluded statuses; no price history is inferred from current list price.", "", "### Representative seven complete date windows", "", "| Cutoff (Singapore midnight) | Products without completed sales | Percentage |", "|---|---:|---:|"]
    cutoffs = sorted(set([spine[0] + pd.Timedelta(days=7), spine[len(spine)//2], spine[-1] + pd.Timedelta(days=1)]))
    for cutoff in cutoffs:
        window = unit_days.loc[:, (unit_days.columns >= cutoff - pd.Timedelta(days=7)) & (unit_days.columns < cutoff)]
        missing = int((window.sum(axis=1) == 0).sum())
        output.append(f"| {cutoff.date()} | {missing} / {len(unit_days)} | {100 * missing / len(unit_days):.2f}% |")
    integrity = not findings and all(c[3] for c in checks) and coverage_ok
    output += ["", "## Integrity result and manual acceptance", "", f"Integrity: {'PASS' if integrity else 'FAIL'}.", "",
               "Dataset acceptance is a separate, explicit decision recorded in data/README.md for the checksummed release. This script does not award a sales-signal or overall acceptance pass. Positive variance can be flat random noise and does not establish useful trend, seasonality or forecasting quality. An integrity failure blocks import regardless of any earlier acceptance decision.", "",
               "Review weekday patterns, product variation and sparse seven-day windows against the intended descriptive sales/inventory use. Generated inventory is correlated with recent sales by construction and cannot validate real stock behaviour. Customer-order distribution and recency diagnostics are deferred with optional ML; no ML analysis is performed.", ""]
    return "\n".join(output), integrity


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("data/raw"))
    args = parser.parse_args()
    output, integrity = profile(args.source)
    destination = Path(__file__).resolve().parents[1] / "data" / "PROFILE.md"
    destination.write_text(output, encoding="utf-8", newline="\n")
    print(f"{destination}: integrity {'PASS' if integrity else 'FAIL'}; dataset acceptance requires a documented manual decision")
    raise SystemExit(0 if integrity else 1)


if __name__ == "__main__":
    main()
